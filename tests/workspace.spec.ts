import { expect, test } from '@playwright/test'

test('Markdown does not execute HTML or javascript links', async ({ page }) => {
  await page.goto('./', { waitUntil: 'domcontentloaded' })
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name: 'Notes', exact: true }).click()
  await page.getByRole('button', { name: 'Create note', exact: true }).click()
  await page.getByLabel('Note content').fill('<img src=x onerror="window.markdownExploit=true">\n\n<script>window.markdownExploit=true</script>\n\n[unsafe](javascript:window.markdownExploit=true)')
  await page.getByTitle('Preview formatted note').click()
  await expect(page.locator('.markdown-preview')).toBeVisible()
  expect(await page.evaluate(() => 'markdownExploit' in window)).toBeFalsy()
  await expect(page.locator('.markdown-preview script, .markdown-preview [onerror], .markdown-preview a[href^="javascript:"]')).toHaveCount(0)
})

for (const width of [320, 390, 768, 1440]) {
  test(`notes and calendar at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: width == 320 ? 568 : width <= 390 ? 667 : 900 })
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('./', { waitUntil: 'domcontentloaded' })
    await expect(page.locator('.calendar-controls h2')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await page.screenshot({ path: `test-results/calendar-${width}.png` })
    const nav = page.getByRole('navigation', { name: 'Main navigation' })
    await nav.getByRole('button', { name: 'Notes' }).click()
    await page.getByRole('button', { name: 'Create note', exact: true }).click()
    await page.getByRole('textbox', { name: 'Note title', exact: true }).fill('Responsive test')
    await page.getByRole('textbox', { name: 'Note content' }).fill('## Saved heading\n\nA persistent thought.')
    const toolbar = page.locator('.editor-format-toolbar')
    expect(await toolbar.evaluate(el => el.scrollWidth <= el.clientWidth)).toBeTruthy()
    await page.getByTitle('Preview formatted note').click()
    await expect(page.getByRole('heading', { name: 'Saved heading' })).toBeVisible()
    await expect(page.getByText('Autosaved', { exact: true })).toBeVisible()
    await page.reload({ waitUntil: 'domcontentloaded' })
    await nav.getByRole('button', { name: 'Notes' }).click()
    await page.locator('.note-list-card').filter({ hasText: 'Responsive test' }).click()
    await expect(page.getByRole('textbox', { name: 'Note content' })).toHaveValue('## Saved heading\n\nA persistent thought.')
    await nav.getByRole('button', { name: 'Calendar', exact: true }).click()
    await page.getByRole('button', { name: 'Next month' }).click()
    const displayedMonth = await page.locator('.calendar-controls h2').innerText()
    await expect(page.locator('.day-title')).toContainText(displayedMonth.split(' ')[0])
    await page.getByRole('button', { name: 'Add an event', exact: true }).click()
    await page.getByLabel('Event title').fill('Linked event')
    await page.getByLabel('All-day event').check()
    await page.getByText('More details', { exact: true }).click()
    await page.getByLabel('Link a note').selectOption({ label: 'Responsive test' })
    await page.getByRole('button', { name: 'Create event', exact: true }).click()
    await expect(page.locator('.selected-day .calendar-event-title')).toHaveText('Linked event')
    await expect(page.locator('.selected-day .calendar-event-title')).toBeVisible()
    await page.locator('.day-event-main').filter({ hasText: 'Linked event' }).click()
    await page.getByLabel('Event title').fill('Updated event')
    await page.getByRole('button', { name: 'Save changes' }).click()
    await expect(page.locator('.day-event-main')).toContainText('Updated event')
    await page.getByRole('button', { name: 'Open note linked to Updated event' }).click()
    await expect(page.getByRole('textbox', { name: 'Note title', exact: true })).toHaveValue('Responsive test')
    await page.getByRole('button', { name: 'Pin note', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Unpin note', exact: true })).toBeVisible()
    if (width <= 700) await page.getByRole('button', { name: 'All notes', exact: true }).first().click()
    await page.getByPlaceholder('Search your notes...').fill('Responsive test')
    await expect(page.locator('.note-list-card')).toHaveCount(1)
    await page.locator('.note-list-card').click()
    await page.screenshot({ path: `test-results/notes-${width}.png` })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await nav.getByRole('button', { name: 'Calendar', exact: true }).click()
    page.on('dialog', dialog => dialog.accept())
    await page.locator('.day-event-main').filter({ hasText: 'Updated event' }).click()
    await page.getByRole('button', { name: 'Delete', exact: true }).click()
    await expect(page.locator('.day-event-main').filter({ hasText: 'Updated event' })).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    expect(errors).toEqual([])
  })
}
