import { expect, test } from '@playwright/test'

for (const width of [320, 375, 1440]) {
  test(`private to-do list workflow at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: width === 320 ? 568 : 760 })
    await page.goto('./', { waitUntil: 'domcontentloaded' })
    await expect(page.locator('.workspace-header')).not.toContainText('Daymark')
    const nav = page.getByRole('navigation', { name: 'Main navigation' })
    await nav.getByRole('button', { name: 'To-do', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'To-do list' })).toBeVisible()
    await page.getByLabel('Task title').fill('Buy groceries')
    await page.getByLabel('Description', { exact: true }).fill('Milk, bread\nAnd something for dinner')
    await page.getByLabel('Due date', { exact: true }).fill('2027-02-03')
    await nav.getByRole('button', { name: 'Calendar', exact: true }).click()
    await nav.getByRole('button', { name: 'To-do', exact: true }).click()
    await expect(page.getByLabel('Task title')).toHaveValue('Buy groceries')
    await expect(page.getByLabel('Description', { exact: true })).toHaveValue('Milk, bread\nAnd something for dinner')
    await expect(page.getByLabel('Due date', { exact: true })).toHaveValue('2027-02-03')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await page.getByRole('button', { name: 'Add task', exact: true }).click()
    await expect(page.locator('.task-row')).toContainText('Buy groceries')
    await expect(page.locator('.task-description')).toHaveText('Milk, bread\nAnd something for dinner')
    await expect(page.locator('.task-due')).toContainText('3 Feb 2027')
    await page.getByRole('button', { name: 'Edit Buy groceries', exact: true }).click()
    await page.getByLabel('Task title').fill('')
    await page.getByRole('button', { name: 'Cancel task edit', exact: true }).click()
    await page.getByRole('button', { name: 'Edit Buy groceries', exact: true }).click()
    await expect(page.getByLabel('Description', { exact: true })).toHaveValue('Milk, bread\nAnd something for dinner')
    await page.getByLabel('Description', { exact: true }).fill('Remember oat milk')
    await page.getByLabel('Due date', { exact: true }).fill('2027-02-04')
    await page.getByLabel('Task title').fill('Buy groceries and milk')
    await page.getByRole('button', { name: 'Save task', exact: true }).click()
    await page.getByRole('checkbox', { name: 'Complete Buy groceries and milk', exact: true }).click()
    await expect(page.locator('.task-completed')).toContainText('Buy groceries and milk')
    await expect(page.locator('.task-completed .task-description')).toHaveText('Remember oat milk')
    await expect(page.locator('.task-completed .task-due')).toContainText('4 Feb 2027')
    await expect(page.getByRole('button', { name: 'All', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await page.getByLabel('Task title').fill('Still to do')
    await page.getByRole('button', { name: 'Add task', exact: true }).click()
    await expect(page.locator('.task-row').first()).toContainText('Still to do')
    await expect(page.locator('.task-row').last()).toHaveClass(/task-completed/)
    expect(await page.locator('.task-completed .task-title').evaluate(el => getComputedStyle(el).textDecorationLine)).toBe('line-through')
    await page.getByRole('button', { name: 'Done', exact: true }).click()
    await expect(page.getByRole('checkbox', { name: 'Reopen Buy groceries and milk', exact: true })).toBeChecked()
    await page.reload({ waitUntil: 'domcontentloaded' })
    await nav.getByRole('button', { name: 'To-do', exact: true }).click()
    await expect(page.locator('.task-row')).toHaveCount(2)
    await expect(page.locator('.task-completed')).toContainText('Buy groceries and milk')
    await expect(page.locator('.task-completed .task-description')).toHaveText('Remember oat milk')
    await expect(page.locator('.task-completed .task-due')).toHaveAttribute('datetime', '2027-02-04')
    await page.getByRole('checkbox', { name: 'Reopen Buy groceries and milk', exact: true }).click()
    await page.getByRole('button', { name: 'Open', exact: true }).click()
    await expect(page.getByRole('checkbox', { name: 'Complete Buy groceries and milk', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await page.screenshot({ path: `test-results/tasks-${width}.png` })
    await page.getByRole('button', { name: 'Delete Buy groceries and milk', exact: true }).click()
    await expect(page.locator('.task-row')).toHaveCount(1)
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    await expect(page.getByRole('checkbox', { name: 'Complete Buy groceries and milk', exact: true })).not.toBeChecked()
    await expect(page.locator('.undo-notice')).toHaveCount(0)
    const restored = page.locator('.task-row').filter({ hasText: 'Buy groceries and milk' })
    await expect(restored.locator('.task-description')).toHaveText('Remember oat milk')
    await expect(restored.locator('.task-due')).toHaveAttribute('datetime', '2027-02-04')
    await page.getByRole('button', { name: 'Edit Buy groceries and milk', exact: true }).click()
    await page.getByLabel('Description', { exact: true }).fill('')
    await page.getByRole('button', { name: 'Clear due date', exact: true }).click()
    await page.getByRole('button', { name: 'Save task', exact: true }).click()
    await expect(restored.locator('.task-description, .task-due')).toHaveCount(0)
  })
}

test('task due dates stay on the chosen calendar day and only open past-due tasks are overdue', async ({ browser }) => {
  const context = await browser.newContext({ timezoneId: 'America/Los_Angeles' })
  const page = await context.newPage()
  try {
    await page.clock.setFixedTime(new Date('2026-11-18T15:00:00Z'))
    await page.goto('http://127.0.0.1:4173/Calender/', { waitUntil: 'domcontentloaded' })
    await page.getByRole('navigation').getByRole('button', { name: 'To-do', exact: true }).click()
    for (const [title, date] of [['Yesterday', '2026-11-17'], ['Today', '2026-11-18']]) {
      await page.getByLabel('Task title').fill(title)
      await page.getByLabel('Due date', { exact: true }).fill(date)
      await page.getByRole('button', { name: 'Add task', exact: true }).click()
    }
    await expect(page.locator('.task-overdue')).toHaveText('Overdue · 17 Nov 2026')
    await expect(page.locator('.task-due').filter({ hasText: 'Due 18 Nov 2026' })).not.toHaveClass(/task-overdue/)
    await page.getByRole('checkbox', { name: 'Complete Yesterday', exact: true }).click()
    await expect(page.locator('.task-overdue')).toHaveCount(0)
    await expect(page.locator('.task-completed .task-due')).toHaveAttribute('datetime', '2026-11-17')
  } finally { await context.close() }
})

test('older browser tasks load with blank optional details', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('daymark_demo_v1', JSON.stringify({notes:[],events:[],tasks:[{id:'legacy',title:'Older task',completed:false,created_at:'2026-11-17T12:00:00Z',updated_at:'2026-11-17T12:00:00Z'}]})))
  await page.goto('./', { waitUntil: 'domcontentloaded' })
  await page.getByRole('navigation').getByRole('button', { name: 'To-do', exact: true }).click()
  await page.getByRole('button', { name: 'Edit Older task', exact: true }).click()
  await expect(page.getByLabel('Description', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('Due date', { exact: true })).toHaveValue('')
  await page.getByLabel('Description', { exact: true }).fill('Updated safely')
  await page.getByRole('button', { name: 'Save task', exact: true }).click()
  await expect(page.locator('.task-description')).toHaveText('Updated safely')
})

test('Undo restores multiple deleted tasks with their original identity and completion status', async ({ page }) => {
  await page.goto('./', { waitUntil: 'domcontentloaded' })
  const nav = page.getByRole('navigation', { name: 'Main navigation' })
  await nav.getByRole('button', { name: 'To-do', exact: true }).click()
  for (const title of ['Finished task', 'Open task']) {
    await page.getByLabel('Task title').fill(title)
    await page.getByRole('button', { name: 'Add task', exact: true }).click()
  }
  await page.getByRole('checkbox', { name: 'Complete Finished task', exact: true }).click()
  const original = await page.evaluate(() => JSON.parse(localStorage.getItem('daymark_demo_v1')!).tasks)
  await page.getByRole('button', { name: 'Delete Finished task', exact: true }).click()
  await page.getByRole('button', { name: 'Delete Open task', exact: true }).click()
  await expect(page.locator('.undo-notice')).toContainText('2 tasks deleted.')
  await nav.getByRole('button', { name: 'Calendar', exact: true }).click()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await nav.getByRole('button', { name: 'To-do', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Complete Open task', exact: true })).toBeVisible()
  await expect(page.locator('.undo-notice')).toContainText('Task deleted.')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Reopen Finished task', exact: true })).toBeChecked()
  const restored = await page.evaluate(() => JSON.parse(localStorage.getItem('daymark_demo_v1')!).tasks)
  expect(restored.sort((a: { id: string }, b: { id: string }) => a.id.localeCompare(b.id))).toEqual(original.sort((a: { id: string }, b: { id: string }) => a.id.localeCompare(b.id)))
})

test('Undo expires after ten seconds and keeps the deletion saved', async ({ page }) => {
  await page.clock.install()
  await page.goto('./', { waitUntil: 'domcontentloaded' })
  await page.getByRole('navigation').getByRole('button', { name: 'To-do', exact: true }).click()
  await page.getByLabel('Task title').fill('Remove me')
  await page.getByRole('button', { name: 'Add task', exact: true }).click()
  await page.getByRole('button', { name: 'Delete Remove me', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeVisible()
  await page.clock.fastForward(10001)
  await expect(page.locator('.undo-notice')).toHaveCount(0)
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.getByRole('navigation').getByRole('button', { name: 'To-do', exact: true }).click()
  await expect(page.locator('.task-row')).toHaveCount(0)
})
